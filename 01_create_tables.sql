-- ============================================================

-- 1. COUNTRIES
CREATE TABLE COUNTRIES (
  COUNTRY_ID       NUMBER(10) PRIMARY KEY,
  COUNTRY_NAME     VARCHAR(20),
  CURRENCY         VARCHAR(20),
  LANGUAGE_SPOKEN  VARCHAR(20)
);

-- 2. TOUR_PACKAGES
CREATE TABLE TOUR_PACKAGES (
  PACKAGE_ID     NUMBER(10) PRIMARY KEY,
  PACKAGE_NAME   VARCHAR(30),
  COUNTRY_ID     NUMBER(10) REFERENCES COUNTRIES(COUNTRY_ID),
  DURATION_DAYS  NUMBER(10),
  PACKAGE_PRICE  NUMBER(10,2),
  PACKAGE_TYPE   VARCHAR(20)
);

-- 3. TOUR_GUIDES
CREATE TABLE TOUR_GUIDES (
  GUIDE_ID         NUMBER(15) PRIMARY KEY,
  GUIDE_NAME       VARCHAR(30),
  EXPERIENCE_YEAR  NUMBER(10),
  LANGUAGE_KNOWN   VARCHAR(40),
  PHONE_NUMBER     VARCHAR(20)
);

-- 4. PACKAGE_GUIDES (mapping: packages <-> guides)
CREATE TABLE PACKAGE_GUIDES (
  PACKAGE_ID  NUMBER(10) REFERENCES TOUR_PACKAGES(PACKAGE_ID),
  GUIDE_ID    NUMBER(15) REFERENCES TOUR_GUIDES(GUIDE_ID),
  PRIMARY KEY (PACKAGE_ID, GUIDE_ID)
);

-- 5. CUSTOMERS
CREATE TABLE CUSTOMERS (
  CUSTOMER_ID      NUMBER(10) PRIMARY KEY,
  CUSTOMER_NAME    VARCHAR(30),
  GENDER           VARCHAR(20),
  PHONE_NUMBER     VARCHAR(20),
  EMAIL            VARCHAR(30),
  CITY             VARCHAR(20),
  PASSPORT_NUMBER  VARCHAR(20) UNIQUE
);

-- 6. BOOKINGS
CREATE TABLE BOOKINGS (
  BOOKING_ID        NUMBER(10) PRIMARY KEY,
  CUSTOMER_ID       NUMBER(10) REFERENCES CUSTOMERS(CUSTOMER_ID),
  PACKAGE_ID        NUMBER(10) REFERENCES TOUR_PACKAGES(PACKAGE_ID),
  BOOKING_DATE      DATE,
  NUMBER_OF_PEOPLE  NUMBER(10),
  BOOKING_STATUS    VARCHAR(20)
);

-- 7. HOTELS
CREATE TABLE HOTELS (
  HOTEL_ID      NUMBER(10) PRIMARY KEY,
  HOTEL_NAME    VARCHAR(30),
  COUNTRY_ID    NUMBER(10) REFERENCES COUNTRIES(COUNTRY_ID),
  CITY          VARCHAR(30),
  HOTEL_RATING  DECIMAL(2,1)
);

-- 8. PACKAGE_HOTELS (mapping: packages <-> hotels)
CREATE TABLE PACKAGE_HOTELS (
  PACKAGE_ID  NUMBER(10) REFERENCES TOUR_PACKAGES(PACKAGE_ID),
  HOTEL_ID    NUMBER(10) REFERENCES HOTELS(HOTEL_ID),
  PRIMARY KEY (PACKAGE_ID, HOTEL_ID)
);

-- 9. PAYMENTS
CREATE TABLE PAYMENTS (
  PAYMENT_ID      NUMBER(10) PRIMARY KEY,
  BOOKING_ID      NUMBER(10) REFERENCES BOOKINGS(BOOKING_ID),
  PAYMENT_DATE    DATE,
  PAYMENT_AMOUNT  DECIMAL(10,2),
  PAYMENT_METHOD  VARCHAR(20),
  PAYMENT_STATUS  VARCHAR(20)
);

-- 10. FLIGHTS
CREATE TABLE FLIGHTS (
  FLIGHT_ID       NUMBER(10) PRIMARY KEY,
  AIRLINE_NAME    VARCHAR(30),
  DEPARTURE_CITY  VARCHAR(30),
  ARRIVAL_CITY    VARCHAR(30),
  FLIGHT_DATE     DATE,
  TICKET_PRICE    DECIMAL(10,2)
);
